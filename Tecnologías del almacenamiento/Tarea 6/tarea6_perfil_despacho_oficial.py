# =========================
# Balance económico preliminar
# =========================

dt_h = 1  # paso horario

# Energía comprada en carga
df["E_comprada_MWh"] = df["P_cmd_MW"].where(
    df["P_cmd_MW"] < 0, 0
).abs() * dt_h

# Energía vendida en descarga
df["E_vendida_MWh"] = df["P_cmd_MW"].where(
    df["P_cmd_MW"] > 0, 0
) * dt_h

# Costo de comprar energía para cargar
df["costo_carga_USD"] = (
    df["E_comprada_MWh"] * df["precio_usd_mwh"]
)

# Ingreso por vender energía en descarga
df["ingreso_descarga_USD"] = (
    df["E_vendida_MWh"] * df["precio_usd_mwh"]
)

# Margen bruto horario
df["flujo_bruto_USD"] = (
    df["ingreso_descarga_USD"] - df["costo_carga_USD"]
)

# =========================
# Resumen para enero + junio
# =========================

resumen_61d = {
    "horas_totales": len(df),
    "dias_simulados": df["fecha"].nunique(),
    "horas_carga": (df["tipo_operacion"] == "carga").sum(),
    "horas_descarga": (df["tipo_operacion"] == "descarga").sum(),
    "E_comprada_MWh": df["E_comprada_MWh"].sum(),
    "E_vendida_MWh": df["E_vendida_MWh"].sum(),
    "precio_promedio_carga_USD_MWh": df.loc[
        df["E_comprada_MWh"] > 0, "precio_usd_mwh"
    ].mean(),
    "precio_promedio_descarga_USD_MWh": df.loc[
        df["E_vendida_MWh"] > 0, "precio_usd_mwh"
    ].mean(),
    "costo_carga_USD": df["costo_carga_USD"].sum(),
    "ingreso_descarga_USD": df["ingreso_descarga_USD"].sum(),
    "margen_bruto_USD": df["flujo_bruto_USD"].sum()
}

resumen_61d = pd.DataFrame([resumen_61d])
pd.set_option("display.float_format", "{:.2f}".format)

