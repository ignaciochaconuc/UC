import pandas as pd

df = pd.read_csv("precios_energia.csv", header=None, names=["timestamp", "precio_usd_mwh"])

df["timestamp"] = pd.to_datetime(df["timestamp"], format="%m/%d/%y %I:%M %p")

#enero y junio

df = df[df["timestamp"].dt.month.isin([1, 6])].copy()
df = df.sort_values("timestamp").reset_index(drop=True)

# Crear columnas útiles
df["fecha"] = df["timestamp"].dt.date
df["hora"] = df["timestamp"].dt.hour

print("Horas enero + junio:", len(df))

# =========================
# encontramos los dos bloques de carga por día
# =========================

P_carga_MW = 100
duracion_bloque_h = 3
n_bloques_carga = 2

# Inicializar perfil de despacho
df["P_cmd_MW"] = 0.0
df["tipo_operacion"] = "reposo"

bloques_carga = []

# =========================
# 3. Buscar bloques por día
# =========================

for fecha, grupo in df.groupby("fecha"):
    grupo = grupo.sort_values("timestamp").copy()

    candidatos = []

    # Revisar todos los bloques consecutivos posibles dentro del día
    for i in range(0, len(grupo) - duracion_bloque_h + 1):
        bloque = grupo.iloc[i:i + duracion_bloque_h]

        # Verificar que el bloque sea realmente continuo
        duracion_real = (
            bloque["timestamp"].iloc[-1] - bloque["timestamp"].iloc[0]
        ).total_seconds() / 3600

        if duracion_real == duracion_bloque_h - 1:
            precio_promedio = bloque["precio_usd_mwh"].mean()
            costo_total = bloque["precio_usd_mwh"].sum() * P_carga_MW

            candidatos.append({
                "fecha": fecha,
                "indices": bloque.index.tolist(),
                "inicio": bloque["timestamp"].iloc[0],
                "fin": bloque["timestamp"].iloc[-1],
                "precio_promedio_usd_mwh": precio_promedio,
                "costo_total_usd": costo_total
            })

    # Ordenar bloques desde el más barato
    candidatos = sorted(candidatos, key=lambda x: x["precio_promedio_usd_mwh"])

    bloques_elegidos = []
    indices_ocupados = set()

    # Elegir 2 bloques sin traslape
    for candidato in candidatos:
        indices_bloque = set(candidato["indices"])

        if indices_ocupados.isdisjoint(indices_bloque):
            bloques_elegidos.append(candidato)
            indices_ocupados.update(indices_bloque)

        if len(bloques_elegidos) == n_bloques_carga:
            break

    # Guardar bloques seleccionados
    for bloque in bloques_elegidos:
        df.loc[bloque["indices"], "P_cmd_MW"] = -P_carga_MW
        df.loc[bloque["indices"], "tipo_operacion"] = "carga"
        bloques_carga.append(bloque)

# Convertir resumen a DataFrame
df_bloques_carga = pd.DataFrame(bloques_carga)

print(df_bloques_carga.head())

df.info()

df_bloques_carga.info()

"""por lo tanto, en **df** tenemos todas las horas de enero y junio combinadas, teniendo un total de 61 x 24 = 1464 horas. en **df_bloques_carga** tendremos los bloques de carga que son 2 horas de carga por día. donde 2 x 61 es 122.

Guardamos el perfil:
"""

df.to_csv("perfil_despacho_carga_2_bloques_diarios.csv", index=False)
df_bloques_carga.to_csv("resumen_bloques_carga.csv", index=False)

