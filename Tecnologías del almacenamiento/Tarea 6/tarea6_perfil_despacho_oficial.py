"""Ahora vamos por los bloques de descarga"""

# =========================
# Parámetros de descarga
# =========================

P_descarga_MW = 74
duracion_bloque_h = 1
n_bloques_descarga = 2

bloques_descarga = []

# =========================
# Buscar bloques de descarga por día
# =========================

for fecha, grupo in df.groupby("fecha"):
    grupo = grupo.sort_values("timestamp").copy()

    candidatos = []

    # Revisar todos los bloques consecutivos posibles dentro del día
    for i in range(0, len(grupo) - duracion_bloque_h + 1):
        bloque = grupo.iloc[i:i + duracion_bloque_h]

        # Verificar que el bloque sea realmente continuo
        duracion_real = (
            bloque["timestamp"].iloc[-1] - bloque["timestamp"].iloc[0]
        ).total_seconds() / 3600

        if duracion_real == duracion_bloque_h - 1:

            # Evitar que el bloque se traslape con horas de carga
            if (bloque["tipo_operacion"] == "carga").any():
                continue

            precio_promedio = bloque["precio_usd_mwh"].mean()
            ingreso_total = bloque["precio_usd_mwh"].sum() * P_descarga_MW

            candidatos.append({
                "fecha": fecha,
                "indices": bloque.index.tolist(),
                "inicio": bloque["timestamp"].iloc[0],
                "fin": bloque["timestamp"].iloc[-1],
                "precio_promedio_usd_mwh": precio_promedio,
                "ingreso_total_usd": ingreso_total
            })

    # Ordenar bloques desde el más caro
    candidatos = sorted(
        candidatos,
        key=lambda x: x["precio_promedio_usd_mwh"],
        reverse=True
    )

    bloques_elegidos = []
    indices_ocupados = set()

    # Elegir 2 bloques sin traslape entre ellos
    for candidato in candidatos:
        indices_bloque = set(candidato["indices"])

        if indices_ocupados.isdisjoint(indices_bloque):
            bloques_elegidos.append(candidato)
            indices_ocupados.update(indices_bloque)

        if len(bloques_elegidos) == n_bloques_descarga:
            break

    # Guardar bloques seleccionados en el DataFrame principal
    for bloque in bloques_elegidos:
        df.loc[bloque["indices"], "P_cmd_MW"] = P_descarga_MW
        df.loc[bloque["indices"], "tipo_operacion"] = "descarga"
        bloques_descarga.append(bloque)

# Convertir resumen a DataFrame
df_bloques_descarga = pd.DataFrame(bloques_descarga)

print(df_bloques_descarga.head())

df_bloques_descarga.info()

"""Guardamos el perfil"""

df.to_csv("perfil_despacho_completo_preliminar.csv", index=False)
df_bloques_descarga.to_csv("resumen_bloques_descarga.csv", index=False)

